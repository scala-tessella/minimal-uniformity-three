  it should "not under-predict chambers for species where a k = 4 tiling is KNOWN to exist" in:
    // The chain gives an UPPER bound on C. Three species have a four-orbit tiling with a known
    // chamber count, so a bound below it would refute the chain outright. Parameters are taken at
    // their weakest admissible setting, anchor tile only, which is the safest form of the bound.
    def weakBound(pointGroup: Int, n: Int, anchorStab: Int, q: Int, k: Int): Int =
      val vLo   = n * (pointGroup / anchorStab)
      val vHi   = vLo + (k - q) * pointGroup
      val faces = pointGroup / anchorStab
      val f     = 2 * vHi - (n * faces - 3 * faces)
      4 * (vHi + f) / pointGroup
    // (3.9.18): 18-gon, observed q = 3, stabiliser of order 6 in a point group of order 6 or 12
    weakBound(6, 18, 6, 3, 4) should be >= 24
    weakBound(12, 18, 12, 2, 4) should be >= 24
    // (5^2.10): the 10-gon is the letter occurring once; observed q = 3 under D2
    weakBound(4, 10, 4, 3, 4) should be >= 18
    weakBound(8, 10, 4, 3, 4) should be >= 18
    // (3.4^2.6): 6-gon, observed q = 3, saturated patterns at 30 chambers
    weakBound(4, 6, 2, 3, 4) should be >= 30
    weakBound(12, 6, 2, 3, 4) should be >= 30

