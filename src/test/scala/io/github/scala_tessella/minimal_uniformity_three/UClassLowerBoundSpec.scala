      else withClue(s"C=$c is below the threshold or even: ")(n should be > 0)

  // ---- the (3.10.15) chain ----------------------------------------------------------------------------

  it should "bound the (3.10.15) four-orbit symbol at 24 chambers, making the 31-48 window vacuous" in:
    val pointGroup                = 12 // p6m, forced by D3 on the 15-gon and D2 on the decagon
    // the 15-gon's three corner orbits have stabiliser orders 2, 1, 1 inside Stab = D3
    val vFrom15                   = List(2, 1, 1).map(pointGroup / _).sum
    vFrom15 shouldBe 30
    vFrom15 shouldBe 2 * 15 // and that is exactly the fifteen-gon corners per primitive cell
    // k <= 4 leaves at most one further vertex orbit, contributing at most 12
    val vMax                      = vFrom15 + pointGroup
    vMax shouldBe 42
    // faces per cell: 15-gons 12/6, decagons 12/4, the six-fold tile 12/12; it is not a regular hexagon,
    // since 6 is not a letter of z, so it carries at least 12 corners
    (pointGroup / 6, pointGroup / 4, pointGroup / 12) shouldBe (2, 3, 1)
    val knownCorners              = 2 * 15 + 3 * 10 + 12
    knownCorners shouldBe 72
    // 2E = sum n_f >= knownCorners + 3(F - 6) and E = V + F, so F <= 2V - 54 and C = 4E/12 = E/3
    def chamberBound(v: Int): Int =
      val f = 2 * v - (knownCorners - 3 * 6)
      val e = v + f
      4 * e / pointGroup
    chamberBound(vMax) shouldBe 24
    chamberBound(vFrom15) shouldBe 12
    // the G0 bound alone would have allowed 12k = 48: the window 31-48 cannot contain a four-orbit symbol
    chamberBound(vMax) should be < 12 * 4

  // ---- the generalised stabiliser chain, applied to the remaining open rows ------------------------------------

  /** The stabiliser counting chain in general. `anchor` is a regular n-gon whose letter occurs ONCE in z (so
    * no vertex meets two copies and corner orbits are read off the stabiliser); `pointGroup` is |G/T|;
    * `anchorStab` the order of Stab(anchor) and `anchorOrbits` its number of corner orbits; `k` the assumed
    * uniformity bound; `knownCorners` / `knownFaces` the corners and count of the face orbits forced to
    * exist. Returns (V low, V high, chamber bound).
    *
    * V is bounded below by the anchor's corners per cell (n · P/s, all distinct) and above by adding the at
    * most k − anchorOrbits remaining orbits at P each. Then 2E = Σ n_f ≥ knownCorners + 3(F − knownFaces)
    * with E = V + F (Euler on the torus) gives F ≤ 2V − (knownCorners − 3·knownFaces), and a symmetry fixing
    * a flag is the identity, so C = 4E/P.
    */
  private def chain(
      pointGroup: Int,
      n: Int,
      anchorStab: Int,
      anchorOrbits: Int,
      k: Int,
      knownCorners: Int,
      knownFaces: Int
  ): (Int, Int, Int) =
    val vLo = n * (pointGroup / anchorStab)
    val vHi = vLo + (k - anchorOrbits) * pointGroup
    val f   = 2 * vHi - (knownCorners - 3 * knownFaces)
    (vLo, vHi, 4 * (vHi + f) / pointGroup)

  it should "reproduce the (3.10.15) chain through the general formula" in:
    chain(
      pointGroup = 12,
      n = 15,
      anchorStab = 6,
      anchorOrbits = 3,
      k = 4,
      knownCorners = 2 * 15 + 3 * 10 + 12,
      knownFaces = 6
    ) shouldBe (30, 42, 24)

  it should "bound (3.7.42) at 21 chambers for k <= 4, inside the searched window" in:
    // under k <= 4 the 42-gon's only surviving stabiliser is D6: D3 and C6 leave 7 orbits, C3 14, C2/D1 21
    val survivors     =
      for
        m   <- admissibleRotations(42)
        dih <- List(false, true)
        q    = if dih then (0 until 42).map(c => cornerOrbits(42, m, Some(c))).min else cornerOrbits(42, m, None)
        if q <= 4
      yield (m, dih, q)
    survivors shouldBe List((6, true, 4))
    // D6 forces point group D6, so p6m. The anchor's 4 corner orbits EXHAUST k = 4: every vertex is a
    // corner of the single 42-gon per cell, and no further vertex orbit exists.
    // Forced faces: the 42-gon (1/cell, 42 corners); heptagons, whose stabiliser is at most a reflection
    // (7 is coprime to every crystallographic order) so at least 12/2 = 6 per cell, 42 corners; triangles,
    // at least 12/6 = 2 per cell, 6 corners.
    val (vLo, vHi, c) = chain(12, 42, 12, 4, 4, 42 + 6 * 7 + 2 * 3, 1 + 6 + 2)
    vLo shouldBe 42
    vHi shouldBe 42   // q = k, so no slack at all
    c shouldBe 21
    c should be <= 24 // inside the exhausted four-orbit window, which holds ZERO (3.7.42) candidates
    c should be < 12 * 4 // and far inside the G0 bound

  it should "bound (4.5.20) at 29 chambers for k <= 4, just outside the searched window" in:
    // under k <= 4 only D4 survives on the 20-gon: C4 and D2 leave 5 orbits, C2/D1 10, C1 20
    val survivors     =
      for
        m   <- admissibleRotations(20)
        dih <- List(false, true)
        q    = if dih then (0 until 20).map(c => cornerOrbits(20, m, Some(c))).min else cornerOrbits(20, m, None)
        if q <= 4
      yield (m, dih, q)
    survivors shouldBe List((4, true, 3))
    // D4 forces point group D4, so P = 8 (no 3-fold is available: 3 divides none of 4, 5, 20)
    // forced faces: the 20-gon (1/cell, 20 corners); pentagons, stabiliser at most a reflection since 5 is
    // coprime to every crystallographic order, so >= 4 per cell and 20 corners; a square, >= 1 per cell
    val (vLo, vHi, c) = chain(8, 20, 8, 3, 4, 20 + 4 * 5 + 4, 1 + 4 + 1)
    vLo shouldBe 20
    vHi shouldBe 28
    c shouldBe 29
    c should be < 12 * 4 // improves on the G0 bound of 48
    // the bound bites only in its worst case: V is 8/|Stab| summed over four orbits, and only a fourth
    // orbit with TRIVIAL stabiliser reaches C > 24 — every other V lands inside the searched window
    val perV = List(20, 22, 24, 28).map(v => v -> (3 * v - (20 + 4 * 5 + 4 - 3 * 6)) / 2)
    perV shouldBe List(20 -> 17, 22 -> 20, 24 -> 23, 28 -> 29)
    perV.filter(_._2 > 24).map(_._1) shouldBe List(28)

  // ---- witness consistency: the corner-orbit lemma against every banked tiling --------------------------

  private def symbolFromKey(key: String): DSymbol =
    val rows          = key.split(";").map(_.trim).filter(_.nonEmpty)
    val n             = rows.length
    val op            = Array.ofDim[Int](n + 1, 3)
    val m01           = Array.ofDim[Int](n + 1)
    val m12           = Array.ofDim[Int](n + 1)
    for (r, i) <- rows.zipWithIndex do
      val Array(ops, ms) = r.split('|')
      val parts          = ops.split(',').map(_.toInt)
      op(i + 1)(0) = parts(0); op(i + 1)(1) = parts(1); op(i + 1)(2) = parts(2)
      m01(i + 1) = parts(3); m12(i + 1) = ms.toInt
    val dset          = new DSet(op)
    val (orbs, index) = DelaneySymbols.collectOrbits(dset)
    val vs            = Array.tabulate(orbs.length): k =>
      val o = orbs(k)
      val d = o.elements.head
      (if o.i == 0 then m01(d) else m12(d)) / o.r
    new DSymbol(dset, orbs, index, vs)

  /** Every corner-orbit count a crystallographic stabiliser of a regular `n`-gon can produce. */
  private def achievableOrbitCounts(n: Int): Set[Int] =
    (for
      m   <- admissibleRotations(n)
      cnt <- cornerOrbits(n, m, None) +: (0 until n).map(c => cornerOrbits(n, m, Some(c)))
    yield cnt).toSet

  it should "not contradict any banked witness (falsification against real tilings)" in:
    // the stabiliser floor says the corners of a regular n-gon whose letter occurs ONCE in z meet at least
    // ceil(n / 2m) vertex orbits. Every banked witness IS a tiling, so a witness whose anchor tile
    // meets FEWER orbits than any crystallographic stabiliser permits would refute the lemma.
    var checked = 0
    for (name, z, k) <- SaturationProbe.entries do
      val ds       = symbolFromKey(k)
      val vertexOs = ds.orbs.zipWithIndex.collect { case (o, idx) if o.i == 1 => idx -> o.elements.toSet }
      val n        = z.max
      if z.count(_ == n) == 1 then
        // the face orbits that ARE regular n-gons: degree n
        for (o, fi) <- ds.orbs.zipWithIndex if o.i == 0 && ds.m(0, 1, o.elements.head) == n do
          val chambers = o.elements.toSet
          val met      = vertexOs.count((_, elems) => (elems & chambers).nonEmpty)
          val allowed  = achievableOrbitCounts(n)
          val floor    = allowed.min
          val uniform  = vertexOs.size
          println(f"$name%-34s anchor $n%2d-gon (orbit $fi%2d): meets $met%2d vertex orbits of $uniform%2d" +
            f"  | lemma floor $floor%2d, achievable ${allowed.toList.sorted.mkString(",")}" +
            (if allowed(met) then "" else "   <-- NOT an achievable stabiliser count"))
          checked += 1
          withClue(s"$name: anchor $n-gon meets $met vertex orbits, below the stabiliser floor $floor: ")(
            met should be >= floor
          )
          withClue(s"$name: anchor meets more orbits than the tiling has: ")(met should be <= uniform)
    checked should be > 5 // the audit must actually have examined witnesses

  // ---- the cap-profile theorem, and the chain at five and six orbits -----------------------------------

  it should "force j+1 vertex orbits to be >= 6-cycles above C = 6(k+j) (cap profile)" in:
    // With at most j orbits at the top cap 24, the largest attainable budget is 24j + 12(k-j), the best
    // remaining cap being 12. Feasibility needs sum12 >= 2C, so 2C > 12(j+k) forces a (j+1)-th orbit to
    // the top cap — attained only by a cycle of length >= 6.
    def maxSumWith(k: Int, j: Int): Int = 24 * j + 12 * (k - j)
    def threshold(k: Int, j: Int): Int  = 6 * (k + j)
    for k <- 2 to 8; j <- 0 until k do
      (2 * threshold(k, j)) shouldBe maxSumWith(k, j)
    // at three orbits the thresholds reproduce the campaign's own window boundaries
    (0 until 3).map(threshold(3, _)) shouldBe Vector(18, 24, 30)
    // and the last one is exactly the odd-slice case, where ALL orbits are cycles and C is therefore even
    threshold(3, 2) shouldBe 12 * 3 - 6
    threshold(4, 3) shouldBe 12 * 4 - 6

  it should "pin the orbit profile of the k = 3 mid-window slices" in:
    // above C = 24 at least two orbits sit at cap 24, so the third satisfies 48 + c3 >= 2C
    def thirdCapAtLeast(c: Int): Int       = 2 * c - 48
    val caps                               = List(4, 6, 8, 12, 24)
    def admissibleThird(c: Int): List[Int] = caps.filter(_ >= thirdCapAtLeast(c)).filter(_ <= 24)
    admissibleThird(25) shouldBe caps
    admissibleThird(27) shouldBe List(6, 8, 12, 24)
    admissibleThird(29) shouldBe List(12, 24)
    admissibleThird(30) shouldBe List(12, 24)
    // at C = 29 a third orbit at cap 24 would make three cycles and force C even (odd slice), so its cap is
    // exactly 12 — a chain of length >= 3 or a 4-cycle — and C odd rules the 4-cycle out: an ODD chain.
    // The measured slice is correspondingly thin: 10 D-sets against 2,014 at C = 28.
    admissibleThird(29).filter(_ < 24) shouldBe List(12)

  it should "bound (3.7.42) at 33 chambers for k <= 5, leaving only 30-33" in:
    // at k <= 5 the 42-gon's only surviving stabiliser is still D6: C6 and D3 leave 7 corner orbits
    val survivors =
      for
        m   <- admissibleRotations(42)
        dih <- List(false, true)
        q    = if dih then (0 until 42).map(c => cornerOrbits(42, m, Some(c))).min else cornerOrbits(42, m, None)
        if q <= 5
      yield (m, dih, q)
    survivors shouldBe List((6, true, 4))
    // forced faces per cell: the 42-gon (1), heptagons (>= 12/2 = 6, since 7 is coprime to every
    // crystallographic rotation order), triangles (>= 12/6 = 2)
    val (_, _, c) = chain(12, 42, 12, 4, 5, 42 + 6 * 7 + 2 * 3, 1 + 6 + 2)
    c shouldBe 33
    c should be < 12 * 5 // the G0 bound would permit 60
    // <= 24 and 25-29 are already exhausted, so the row's k >= 6 needs four chamber counts
    (30 to c).toList shouldBe List(30, 31, 32, 33)

  it should "bound (3.7.42) at 45 chambers for k <= 6" in:
    val (_, _, c) = chain(12, 42, 12, 4, 6, 42 + 6 * 7 + 2 * 3, 1 + 6 + 2)
    c shouldBe 45
    c should be < 12 * 6

  it should "bound (4.5.20) at 41 chambers for k <= 5" in:
    // three stabiliser types survive k <= 5 on the 20-gon; the WEAKEST bound governs
    val survivors =
      for
        m   <- admissibleRotations(20)
        dih <- List(false, true)
        q    = if dih then (0 until 20).map(c => cornerOrbits(20, m, Some(c))).min else cornerOrbits(20, m, None)
        if q <= 5
      yield (m, dih, q)
    survivors.map(_._3).sorted shouldBe List(3, 5, 5)
    // D4 on the 20-gon, point group D4 so P = 8: pentagons >= 8/2 = 4 per cell, one square
    val d4        = chain(8, 20, 8, 3, 5, 20 + 4 * 5 + 4, 1 + 4 + 1)._3
    // C4 or D2 (order 4) with P = 8: two 20-gons per cell, five corner orbits and no slack left
